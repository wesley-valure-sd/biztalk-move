-- One scan of ImportLog. ilExternalReference has no index (KB D21).
SELECT
    x.ilExternalReference AS f8,
    x.ilDateTime, x.ilImportState, x.ilLogLevel, x.ilProcess, x.ilFileName,
    CAST(x.ilMessage AS nvarchar(4000)) AS ilMessage,
    ROW_NUMBER() OVER (PARTITION BY x.ilExternalReference ORDER BY x.ilDateTime DESC) AS rn,
    COUNT(*)     OVER (PARTITION BY x.ilExternalReference)                            AS n
INTO #il
FROM dbo.ImportLog x
WHERE x.ilExternalReference IN (SELECT f8 FROM #S);

DECLARE @from datetime = (SELECT DATEADD(MINUTE, -10, MIN(ilDateTime)) FROM #il);
DECLARE @to   datetime = (SELECT DATEADD(MINUTE,  10, MAX(ilDateTime)) FROM #il);

SELECT
    t.transReference, t.transDateTime, t.transDateTimePosted, t.transAmount, t.transDueNowAmount,
    t.transTotalDueAmount, t.transProductionAmount, t.transIsGroup, t.transRouting,
    t.transCheckNumber, t.transNote, tt.ttypCode
INTO #tx
FROM dbo.[Transaction] t
LEFT JOIN dbo.TransactionType tt ON tt.ttypGUID = t.ttypGUID
WHERE t.transReference IN (SELECT trace FROM #S)
  AND t.transDateTime BETWEEN @from AND @to;

SELECT
    u.utReference, u.utDateTime, u.utAmount, u.ptPaymentTypeCode,
    CAST(u.utErrorMessage AS nvarchar(4000)) AS utErrorMessage
INTO #ut
FROM dbo.UnmappedTransaction u
WHERE u.utReference IN (SELECT trace FROM #S)
  AND u.utDateTime BETWEEN @from AND @to;

SELECT
    s.label,
    s.expected_state,
    s.amount                                                   AS file_amount,
    i.n                                                        AS import_rows,
    i.ilImportState                                            AS il_state,
    i.ilLogLevel                                               AS il_level,
    i.ilProcess                                                AS il_process,
    CASE WHEN i.ilFileName IS NULL THEN NULL
         WHEN i.ilFileName LIKE N'%[\/]%' THEN 0 ELSE 1 END    AS il_file_name_only,
    CASE WHEN i.ilMessage IS NULL THEN NULL
         WHEN CHARINDEX(N' :: ', i.ilMessage) = 0 THEN N'(no tail)'
         ELSE REPLACE(LTRIM(SUBSTRING(i.ilMessage, CHARINDEX(N' :: ', i.ilMessage) + 4, 4000)), s.f8, N'<F8>') END AS il_msg_tail,
    tc.n                                                       AS txn_rows,
    tx.transAmount                                             AS txn_amount,
    tx.transDueNowAmount                                       AS due_now,
    tx.transTotalDueAmount                                     AS total_due,
    tx.transProductionAmount                                   AS production,
    tx.transIsGroup                                            AS is_group,
    tx.ttypCode                                                AS ttyp_code,
    CASE WHEN tx.transReference IS NULL THEN NULL
         WHEN NULLIF(LTRIM(RTRIM(tx.transRouting)), N'') IS NULL THEN 0 ELSE 1 END AS routing_present,
    CASE WHEN tx.transReference IS NULL THEN NULL
         WHEN ISNULL(CONVERT(varchar(20), tx.transCheckNumber), '') = ISNULL(CASE WHEN s.trace NOT LIKE N'%[^0-9]%' AND LEN(s.trace) <= 18 THEN CASE WHEN CONVERT(bigint, s.trace) <= 2147483647 THEN CONVERT(varchar(20), CONVERT(bigint, s.trace)) END END, '') THEN 1 ELSE 0 END AS check_no_ok,
    CASE WHEN tx.transReference IS NULL THEN NULL
         WHEN tx.transDateTime = tx.transDateTimePosted THEN 1 ELSE 0 END AS posted_equals_trans,
    CASE WHEN CHARINDEX(N', Lockbox:', tx.transNote) > 0
         THEN LEFT(tx.transNote, CHARINDEX(N', Lockbox:', tx.transNote) - 1) END AS note_head,
    uc.n                                                       AS ut_rows,
    ux.utAmount                                                AS ut_amount,
    ux.ptPaymentTypeCode                                       AS ut_payment_type,
    CASE WHEN ux.utErrorMessage IS NULL THEN NULL
         WHEN CHARINDEX(N' :: ', ux.utErrorMessage) = 0 THEN N'(no tail)'
         ELSE REPLACE(LTRIM(SUBSTRING(ux.utErrorMessage, CHARINDEX(N' :: ', ux.utErrorMessage) + 4, 4000)), s.f8, N'<F8>') END AS ut_msg_tail
INTO #R
FROM #S s
LEFT JOIN #il i ON i.f8 = s.f8 AND i.rn = 1
OUTER APPLY (SELECT COUNT(*) AS n FROM #tx t
             WHERE t.transReference = s.trace
               AND t.transDateTime BETWEEN DATEADD(MINUTE, -10, i.ilDateTime) AND DATEADD(MINUTE, 10, i.ilDateTime)) tc
OUTER APPLY (SELECT TOP (1) t.* FROM #tx t
             WHERE t.transReference = s.trace
               AND t.transDateTime BETWEEN DATEADD(MINUTE, -10, i.ilDateTime) AND DATEADD(MINUTE, 10, i.ilDateTime)
             ORDER BY t.transDateTime DESC) tx
OUTER APPLY (SELECT COUNT(*) AS n FROM #ut u
             WHERE u.utReference = s.trace
               AND u.utDateTime BETWEEN DATEADD(MINUTE, -10, i.ilDateTime) AND DATEADD(MINUTE, 10, i.ilDateTime)) uc
OUTER APPLY (SELECT TOP (1) u.* FROM #ut u
             WHERE u.utReference = s.trace
               AND u.utDateTime BETWEEN DATEADD(MINUTE, -10, i.ilDateTime) AND DATEADD(MINUTE, 10, i.ilDateTime)
             ORDER BY u.utDateTime DESC) ux;

